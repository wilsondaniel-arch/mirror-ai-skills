/**
 * Builds the report indexes on superapp-workspace main:
 *
 *   reports/home.md          one row per app: its latest report (also written as
 *                            reports/README.md so Bitbucket shows it under the folder)
 *   reports/<app>/README.md  that app's reports grouped by sprint (branch),
 *                            newest sprint first, newest report first
 *
 *   node --experimental-strip-types src/reports-home.ts <reports_dir> [--apps caribbean,panama,lcpr]
 *
 * Every report folder holds run.json (written by run-meta.ts and ark-publish.sh);
 * `generatedBy` in it names who ran the audit. Folder names follow
 * <App>_<Modules or ALL>_<Generated by>_<YYYY-MM-DD_HHMM> (see reportFolderName).
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

export type Run = {
  app?: string;
  market?: string;
  date?: string;
  scope?: string;
  modules?: string[];
  branch?: string;
  android?: { branch?: string; commit?: string };
  ios?: { branch?: string; commit?: string };
  sessionId?: string;
  jiraKey?: string;
  jiraUrl?: string;
  generatedBy?: string;
};
export type Report = { folder: string; run: Run; files: string[] };

export const APP_NAMES: Record<string, string> = { caribbean: "Caribbean", panama: "Panama", lcpr: "LCPR" };
const appName = (id: string) => APP_NAMES[id] ?? id.charAt(0).toUpperCase() + id.slice(1);

/** `Caribbean_BILL_PAYMENT-BILL_HISTORY_Wilson-Daniel_2026-11-12_0925` / `Caribbean_ALL_..._2026-11-13_0836`. */
export function reportFolderName(appId: string, run: Run): string {
  const who = (run.generatedBy || "unknown").trim().replace(/\s+/g, "-");
  const what = run.scope === "project" || !run.modules?.length ? "ALL" : run.modules.join("-");
  const d = run.date ? new Date(run.date) : new Date();
  const stamp = `${d.toISOString().slice(0, 10)}_${d.toISOString().slice(11, 16).replace(":", "")}`;
  return `${appName(appId)}_${what}_${who}_${stamp}`.replace(/[^A-Za-z0-9_.+-]/g, "-");
}

/** Sprint group for a branch: `caribbean/release/sprint-20` -> `Sprint-20`, `feature/Sprint-21` -> `Sprint-21`, else the branch. */
export function sprintOf(branch?: string): string {
  const m = /sprint[-_ ]?(\d+)/i.exec(branch ?? "");
  return m ? `Sprint-${m[1]}` : branch || "Unknown branch";
}

const fmtDate = (iso?: string) => (iso ? `${iso.slice(0, 10)} ${iso.slice(11, 16)} UTC` : "—");
const what = (r: Run) => (r.scope === "project" || !r.modules?.length ? "ALL (full report)" : r.modules.join(", "));
const enc = (p: string) => p.split("/").map(encodeURIComponent).join("/");
const cell = (s: string) => s.replace(/\|/g, "\\|");

export function readReports(appDir: string): Report[] {
  if (!existsSync(appDir)) return [];
  return readdirSync(appDir)
    .filter((f) => statSync(path.join(appDir, f)).isDirectory() && existsSync(path.join(appDir, f, "run.json")))
    .map((folder) => ({ folder, run: JSON.parse(readFileSync(path.join(appDir, folder, "run.json"), "utf8")) as Run, files: readdirSync(path.join(appDir, folder)) }))
    .sort((a, b) => String(b.run.date).localeCompare(String(a.run.date)));
}

export function appIndex(appId: string, reports: Report[]): string {
  const out = [`# ${appName(appId)} — Mirror AI reports`, "", `[← All apps](../home.md)`, ""];
  if (!reports.length) return [...out, "No reports yet.", ""].join("\n");
  out.push("Report name: `<App>_<Modules or ALL>_<Generated by>_<Date>`. Latest sprint and latest report first.", "");
  const groups = new Map<string, Report[]>();
  for (const r of reports) {
    const k = sprintOf(r.run.branch);
    groups.set(k, [...(groups.get(k) ?? []), r]);
  }
  for (const [sprint, list] of groups) {
    out.push(`## ${sprint}`, "", "| Report name | Generated by / Assignee | Modules | Branch | Date | Jira | Report |", "|---|---|---|---|---|---|---|");
    for (const r of list) {
      const html = r.files.includes("parity-report.html") ? `[HTML](${enc(`${r.folder}/parity-report.html`)})` : "";
      const md = r.files.includes("parity-report.md") ? `[MD](${enc(`${r.folder}/parity-report.md`)})` : "";
      out.push(
        `| [${cell(r.folder)}](${enc(r.folder)}/) | ${cell(r.run.generatedBy || "—")} | ${cell(what(r.run))} | \`${cell(r.run.branch || "—")}\` | ${fmtDate(r.run.date)} | ${r.run.jiraKey && r.run.jiraUrl ? `[${r.run.jiraKey}](${r.run.jiraUrl})` : "—"} | ${[html, md].filter(Boolean).join(" · ")} |`,
      );
    }
    out.push("");
  }
  return out.join("\n");
}

export function homeIndex(apps: { id: string; reports: Report[] }[]): string {
  const out = [
    "# Mirror AI — Android/iOS parity reports",
    "",
    "Latest report per app. Click the app for its full history (grouped by sprint), or HTML to open the latest report.",
    "",
    "| App | Report name | Generated by / Assignee | Branch | Date | Report |",
    "|---|---|---|---|---|---|",
  ];
  for (const a of apps) {
    const r = a.reports[0];
    if (!r) {
      out.push(`| [${appName(a.id)}](${a.id}/README.md) | No reports yet | — | — | — | — |`);
      continue;
    }
    out.push(
      `| [${appName(a.id)}](${a.id}/README.md) | ${cell(r.folder)} | ${cell(r.run.generatedBy || "—")} | \`${cell(r.run.branch || "—")}\` | ${fmtDate(r.run.date)} | [HTML](${enc(`${a.id}/${r.folder}/parity-report.html`)}) · [Folder](${enc(`${a.id}/${r.folder}`)}/) |`,
    );
  }
  out.push("");
  return out.join("\n");
}

export function main(argv: string[]): number {
  const dir = argv.find((a, k) => !a.startsWith("--") && argv[k - 1] !== "--apps");
  if (!dir) {
    console.error("Usage: node src/reports-home.ts <reports_dir> [--apps caribbean,panama,lcpr]");
    return 1;
  }
  const k = argv.indexOf("--apps");
  const ids = k >= 0 ? argv[k + 1].split(",") : readdirSync(dir).filter((f) => statSync(path.join(dir, f)).isDirectory());
  const apps = ids.map((id) => ({ id, reports: readReports(path.join(dir, id)) }));
  for (const a of apps) writeFileSync(path.join(dir, a.id, "README.md"), appIndex(a.id, a.reports));
  // home.md is the named index; README.md carries the same table because Bitbucket only
  // renders a folder's README.* under its file listing.
  writeFileSync(path.join(dir, "home.md"), homeIndex(apps));
  writeFileSync(path.join(dir, "README.md"), homeIndex(apps));
  console.error(`home.md + ${apps.length} app index(es) written in ${dir}`);
  return 0;
}

const entry = process.argv[1] ? pathToFileURL(path.resolve(process.argv[1])).href : "";
if (import.meta.url === entry) process.exit(main(process.argv.slice(2)));
